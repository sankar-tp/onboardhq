async function chooseFile(name,type,body='fictional test data') {
  await browser.evaluate((name,type,body) => {
    const input = document.querySelector('dialog[open] input[type="file"]')
    const transfer = new DataTransfer(); transfer.items.add(new File([body],name,{type})); input.files=transfer.files
    input.dispatchEvent(new Event('change',{bubbles:true}))
  },name,type,body)
}
