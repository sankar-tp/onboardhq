async function field(label,value) {
  const selector = await browser.evaluate(label => {
    const dialog = [...document.querySelectorAll('dialog[open]')].at(-1)
    const field = [...dialog.querySelectorAll('label')].find(el => el.querySelector('span')?.textContent === label)
    if (!field) throw Error(`Missing field ${label}`)
    return `#${CSS.escape(field.htmlFor)}`
  },label)
  await browser.fill(selector,value)
}
